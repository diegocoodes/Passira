import { test, expect } from '@playwright/test';
const origin = 'http://127.0.0.1:3100';

test('administrator manages products and the customer follows a real numbered order', async ({ page, browser, request }) => {
  const browserErrors: string[] = [];
  await page.addInitScript(() => {
    const state = window as unknown as { toneStarts: number };
    state.toneStarts = 0;
    class TestAudioContext {
      state = 'suspended'; currentTime = 0; destination = {};
      async resume() { this.state = 'running'; }
      async close() { this.state = 'closed'; }
      createOscillator() { return { type: '', frequency: { value: 0 }, onended: null, connect() {}, disconnect() {}, start() { state.toneStarts++; }, stop() {} }; }
      createGain() { return { gain: { setValueAtTime() {}, linearRampToValueAtTime() {} }, connect() {}, disconnect() {} }; }
    }
    Object.defineProperty(window, 'AudioContext', { value: TestAudioContext });
  });
  page.on('pageerror', error => browserErrors.push(error.message));
  expect((await request.get('/api/admin/dashboard/')).status()).toBe(401);
  expect((await request.post('/api/admin/products/', { data: {}, headers: { origin } })).status()).toBe(401);
  expect((await request.post('/api/admin/login/', { data: {}, headers: { origin: 'https://invalid.example' } })).status()).toBe(403);
  await page.goto('/admin/');
  await expect(page).toHaveURL(/\/admin\/entrar\//);
  await page.getByLabel('Email', { exact: true }).fill('teste@passira.local');
  await page.getByLabel('Senha', { exact: true }).fill('senha-apenas-para-testes-123456');
  await page.getByRole('button', { name: 'Entrar no painel' }).click();
  await expect(page.getByRole('heading', { name: 'Sua operação, à vista.' })).toBeVisible();
  await page.getByRole('button', { name: 'Ativar avisos sonoros', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Desativar avisos sonoros', exact: true })).toHaveAttribute('aria-pressed', 'true');
  expect(await page.evaluate(() => (window as unknown as { toneStarts: number }).toneStarts)).toBe(2);
  await page.getByRole('button', { name: 'Produtos', exact: true }).click();
  await page.getByRole('button', { name: 'Novo produto', exact: true }).click();
  await page.getByLabel('Nome do produto', { exact: true }).fill('Prato de teste do painel');
  await page.getByLabel('Categoria', { exact: true }).selectOption('274522');
  await page.getByLabel('Descrição e ingredientes', { exact: true }).fill('Arroz, frango e salada. Serve duas pessoas.');
  await page.getByLabel('Preço de referência (R$)', { exact: true }).fill('49,90');
  await page.getByLabel('Custo de produção por unidade (R$)', { exact: true }).fill('20,00');
  await page.getByRole('button', { name: 'Salvar produto', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Seu cardápio' })).toBeVisible();
  await page.getByLabel('Buscar produtos').fill('Prato de teste do painel');
  await expect(page.locator('.admin-product-row')).toHaveCount(1);
  const menu = await (await request.get('/api/menu/')).json();
  const product = menu.products.find((product: { name: string }) => product.name === 'Prato de teste do painel');
  expect(product).toBeTruthy();
  const customerContext = await browser.newContext({ baseURL: origin });
  const customer = await customerContext.newPage();
  let whatsappUrl = '';
  await customerContext.route('https://wa.me/**', async route => { whatsappUrl = route.request().url(); await route.fulfill({ status: 200, contentType: 'text/html', body: '<title>WhatsApp test</title><p>Mensagem pronta para envio</p>' }); });
  customer.on('pageerror', error => browserErrors.push(error.message));
  let submitted: Record<string, unknown> | undefined;
  customer.on('request', req => { if (req.url().endsWith('/api/orders/') && req.method() === 'POST') submitted = req.postDataJSON(); });
  await customer.goto(`/produto/${product.id}/`);
  await expect(customer.getByRole('heading', { name: product.name })).toBeVisible();
  await expect(customer.getByRole('dialog')).toHaveCount(0);
  await customer.getByRole('button', { name: 'Aumentar Quantidade', exact: true }).click();
  await customer.getByRole('button', { name: /Adicionar ao carrinho/ }).click();
  await customer.getByRole('link', { name: 'Ver carrinho', exact: true }).click();
  await customer.getByRole('button', { name: 'Continuar para meus dados' }).click();
  await customer.getByLabel('Seu nome', { exact: true }).fill('Cliente Teste');
  await customer.getByLabel('CPF', { exact: true }).fill('52998224725');
  await expect(customer.getByLabel('CPF', { exact: true })).toHaveValue('529.982.247-25');
  await customer.getByLabel('Telefone com DDD', { exact: true }).fill('81999999999');
  // Product editing must preserve the customer's unfinished checkout.
  await customer.getByRole('button', { name: 'Voltar', exact: true }).click();
  await customer.getByRole('link', { name: `Editar ${product.name}` }).click();
  await customer.getByRole('button', { name: /Salvar alterações/ }).click();
  await customer.getByRole('link', { name: 'Ver carrinho', exact: true }).click();
  await customer.getByRole('button', { name: 'Continuar para meus dados' }).click();
  await expect(customer.getByLabel('Seu nome', { exact: true })).toHaveValue('Cliente Teste');
  await expect(customer.getByLabel('CPF', { exact: true })).toHaveValue('529.982.247-25');
  await customer.getByRole('button', { name: 'Conferir pedido' }).click();
  const whatsappPagePromise = customerContext.waitForEvent('page');
  await customer.getByRole('button', { name: /Concluir pedido/ }).click();
  const whatsappPage = await whatsappPagePromise;
  await expect(customer.getByRole('heading', { name: 'Seu pedido chegou!' })).toBeVisible();
  await expect.poll(() => whatsappUrl).toContain('wa.me');
  expect(new URL(whatsappUrl).searchParams.get('text')).toContain('CPF: 529.982.247-25');
  await whatsappPage.close();
  expect(submitted).toBeTruthy();
  const repeat = await customerContext.request.post('/api/orders/', { data: submitted, headers: { origin } });
  expect(repeat.status()).toBe(200);
  const order = await repeat.json();
  expect(order.number).toBe(1); expect(order.totalCents).toBe(9980);
  expect((await request.get('/api/orders/1/')).status()).toBe(404);
  await customer.getByRole('link', { name: 'Acompanhar pedido' }).click();
  await expect(customer.getByRole('heading', { name: 'Pedido #1', exact: true })).toBeVisible();
  await expect(customer.locator('.order-status')).toHaveText('Recebido');
  const tracker = await customerContext.newPage();
  await tracker.goto('/');
  await tracker.getByRole('link', { name: 'Rastrear pedido', exact: true }).click();
  await tracker.getByLabel('Número do pedido').fill('#1');
  await tracker.getByRole('button', { name: 'Rastrear pedido', exact: true }).click();
  await expect(tracker.getByRole('heading', { name: 'Pedido #1', exact: true })).toBeVisible();
  const publicTracking = await (await request.get('/api/orders/number/1/')).json();
  expect(publicTracking.status).toBe('received');
  for (const key of ['customer', 'token', 'items', 'requestKey']) expect(publicTracking).not.toHaveProperty(key);
  await expect(tracker.locator('body')).not.toContainText('529.982.247-25');
  await expect(tracker.locator('body')).not.toContainText('Cliente Teste');
  await page.getByRole('button', { name: 'Pedidos', exact: true }).click();
  await page.getByRole('button', { name: 'Atualizar painel' }).click();
  await expect(page.getByRole('alert').filter({ hasText: 'Novo pedido #1 recebido.' })).toBeVisible();
  expect(await page.evaluate(() => (window as unknown as { toneStarts: number }).toneStarts)).toBe(4);
  const card = page.locator('.admin-order').filter({ hasText: 'Pedido #1' });
  await card.locator('summary').click();
  await page.evaluate(() => { window.print = () => { document.body.dataset.printRequested = 'true'; }; });
  await card.getByRole('button', { name: 'Imprimir comanda', exact: true }).click();
  await expect(page.locator('#passira-print-receipt pre')).toContainText('COMANDA 1');
  await expect(page.locator('#passira-print-receipt pre')).toContainText(product.name);
  await expect(page.locator('#passira-print-receipt pre')).not.toContainText('529.982.247-25');
  expect(await page.locator('body').getAttribute('data-print-requested')).toBe('true');
  await page.evaluate(() => window.dispatchEvent(new Event('afterprint')));
  await expect(page.locator('#passira-print-receipt')).toHaveCount(0);
  await card.getByRole('button', { name: 'Aceitar pedido' }).click();
  await expect(customer.locator('.order-status')).toHaveText('Aceito', { timeout: 25000 });
  await expect(tracker.locator('.order-status')).toHaveText('Aceito', { timeout: 25000 });
  for (const label of ['Iniciar preparo', 'Marcar como pronto', 'Concluir pedido']) await card.getByRole('button', { name: label, exact: true }).click();
  await customer.reload();
  await expect(customer.locator('.order-status')).toHaveText('Concluído');
  await tracker.reload();
  await expect(tracker.locator('.order-status')).toHaveText('Concluído');
  await tracker.getByLabel('Número do pedido').fill('999999');
  await tracker.getByRole('button', { name: 'Rastrear pedido', exact: true }).click();
  await expect(tracker.getByRole('alert').filter({ hasText: 'Pedido não encontrado' })).toBeVisible();
  await tracker.getByLabel('Número do pedido').fill('1');
  await tracker.getByRole('button', { name: 'Rastrear pedido', exact: true }).click();
  await expect(tracker.getByRole('heading', { name: 'Pedido #1', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Despesas', exact: true }).click();
  await page.getByLabel('Descrição', { exact: true }).fill('Despesa de teste');
  await page.getByLabel('Valor (R$)', { exact: true }).fill('9,80');
  await page.getByRole('button', { name: 'Adicionar despesa' }).click();
  await expect(page.locator('.admin-expense-row')).toHaveCount(1);
  const report = await (await page.request.get('/api/admin/dashboard/')).json();
  expect(report.completed).toBe(1); expect(report.received).toBe(1); expect(report.profit).toBe(5000); expect(report.topProducts[0].quantity).toBe(2);
  const highlights = await (await request.get('/api/menu/highlights/')).json();
  expect(highlights.productIds).toContain(product.id);
  expect(Object.keys(highlights).sort()).toEqual(['periodDays', 'productIds']);
  const storefront = await customerContext.newPage();
  await storefront.goto('/');
  await storefront.getByLabel('Buscar no cardápio').fill(product.name);
  await expect(storefront.locator('#menu-products .best-seller-label')).toHaveText('Mais pedidos');
  await storefront.close();
  await page.getByRole('button', { name: 'Visão geral', exact: true }).click();
  await page.screenshot({ path: 'test-results/admin-desktop.png', fullPage: true });
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    if (width === 390) await page.screenshot({ path: 'test-results/admin-mobile.png', fullPage: true });
    await tracker.setViewportSize({ width, height: 900 });
    await expect.poll(() => tracker.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
    if (width === 390) await tracker.screenshot({ path: 'test-results/tracking-mobile.png', fullPage: true });
  }
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Produtos', exact: true }).click();
  await page.getByRole('button', { name: `Editar ${product.name}` }).click();
  await page.getByLabel('Nome do produto', { exact: true }).fill('Prato atualizado pelo painel');
  await page.getByLabel('Preço de referência (R$)', { exact: true }).fill('59,90');
  await page.getByRole('button', { name: 'Salvar produto', exact: true }).click();
  await page.getByLabel('Buscar produtos').fill('Prato atualizado pelo painel');
  await expect(page.locator('.admin-product-row')).toHaveCount(1);
  await customer.goto(`/produto/${product.id}/`);
  await expect(customer.getByRole('heading', { name: 'Prato atualizado pelo painel' })).toBeVisible();
  page.once('dialog', dialog => dialog.accept());
  await page.getByRole('button', { name: 'Excluir Prato atualizado pelo painel', exact: true }).click();
  await expect(page.locator('.admin-product-row')).toHaveCount(0);
  const history = await (await customerContext.request.get(`/api/orders/${order.token}/`)).json();
  expect(history.items[0].title).toBe(product.name); expect(history.items[0].unitCents).toBe(4990);
  expect(browserErrors).toEqual([]);
  await customerContext.close();
  await page.getByRole('button', { name: 'Sair do painel', exact: true }).click();
  await expect(page).toHaveURL(/\/admin\/entrar\//);
  expect((await page.request.get('/api/admin/catalog/')).status()).toBe(401);
});
